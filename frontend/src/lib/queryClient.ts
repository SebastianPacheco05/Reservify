import { QueryClient } from "@tanstack/react-query";

/** Cliente global: cache para no repetir GET al volver de pestaña / segundo plano */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 5 * 60 * 1000,
      gcTime: 30 * 60 * 1000,
      refetchOnWindowFocus: false,
      refetchOnReconnect: false,
      retry: 1,
    },
  },
});
